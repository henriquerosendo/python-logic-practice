# 🔹 Exercício 1 — Função com retorno

# Crie uma função chamada quadrado que receba um número e retorne o quadrado dele.
def quadrado(numero):
    return numero ** 2
num = int(input("Digite um número para calcular o quadrado: "))
resultado = quadrado(num)
print(f"O quadrado de {num} é {resultado}")
